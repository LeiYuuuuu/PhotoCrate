_PRE = (STUDIO, "图像", "滤镜预设（新建调整图层）")


def _adj(id, item, how, keys, see=()):
    return _f(id, item, _ADJ + (item,), how, keys, ("menu", _ADJ[1:] + (item,)), see=see)


def _flt(id, sub, item, how, keys, shortcut="", see=()):
    path = (STUDIO, "滤镜") + ((sub,) if sub else ()) + (item,)
    return _f(id, item.rstrip("…"), path, how, keys, ("menu", path[1:]), shortcut, see)


