@dataclass(frozen=True)
class Feature:
    id: str
    title: str
    path: tuple[str, ...]
    how: str
    keys: tuple[str, ...]
    go: tuple | None = None
    shortcut: str = ""
    see: tuple[str, ...] = field(default=())        # 相关功能的 id

    @property
    def mode(self) -> int:
        return 1 if self.path and self.path[0] == STUDIO else 0


def _f(id, title, path, how, keys, go=None, shortcut="", see=()):
    return Feature(id, title, tuple(path), how, tuple(keys.split()), go, shortcut, tuple(see))


